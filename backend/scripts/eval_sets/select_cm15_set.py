"""
select_cm15_set.py
------------------
Chooses, freezes and checks the 30-receipt set for CM-15.

CM-15 compares OCR accuracy with and without the correction memory, so every
receipt in the set has to reach the vision model and receive a corrections
block. Measured on the live database, 179 of 205 PDF receipts are handled by the
text parser in ``pdf_parser`` and never reach the model, and that parser never
sees the corrections block. So the set is image receipts only.

Selection rule, per store, newest first:
  - completed, with an image file (not a PDF, not pasted text)
  - scoreable by ``ocr_eval.py``: stored ``ocr_data`` holds items, and the
    receipt has saved items to score against
  - at least ``MIN_ITEMS`` saved items. A one-item receipt swings its score
    from 100% to 0% on a single mistake. This is a noise filter chosen for this
    eval, not a threshold measured from the data.

Allocation across the five stores with the most image receipts:
Rainbow Grocery 8, Costco 7, Whole Foods Market 6, Safeway 5, Kukje Market 4.

Run from backend/:

    uv run python scripts/eval_sets/select_cm15_set.py           # choose and write
    uv run python scripts/eval_sets/select_cm15_set.py --check   # verify on this machine

    --check   read the frozen list and confirm every receipt exists, is
              scoreable, and has its image on disk. Run this on the machine
              that will run the model, before starting. Writes nothing.
    --output  where to write the list (default: next to this script)
"""

import argparse
import json
import os
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from app.database import SessionLocal
from app.models import Receipt, Store
from app.models.receipt import ReceiptItem

ALLOCATION = {
    "Rainbow Grocery": 8,
    "Costco": 7,
    "Whole Foods Market": 6,
    "Safeway": 5,
    "Kukje Market": 4,
}
MIN_ITEMS = 3
DEFAULT_OUTPUT = Path(__file__).parent / "cm15_image_30.txt"


def _is_image(receipt: Receipt) -> bool:
    return bool(receipt.image_path) and not receipt.image_path.lower().endswith(".pdf")


def _has_scoreable_ocr(receipt: Receipt) -> bool:
    if not receipt.ocr_data:
        return False
    try:
        data = json.loads(receipt.ocr_data)
    except (json.JSONDecodeError, TypeError):
        return False
    return isinstance(data, dict) and bool(data.get("items"))


def choose(db) -> list[tuple[str, Receipt, int]]:
    """(store, receipt, item count) for the chosen set, in allocation order."""
    item_counts = Counter(rid for (rid,) in db.query(ReceiptItem.receipt_id).all())
    store_ids = {name: sid for sid, name in db.query(Store.id, Store.name).all()}

    chosen: list[tuple[str, Receipt, int]] = []
    for store, wanted in ALLOCATION.items():
        sid = store_ids.get(store)
        if sid is None:
            raise SystemExit(f"Store {store!r} not found in this database.")
        candidates = (
            db.query(Receipt)
            .filter(Receipt.store_id == sid, Receipt.status == "completed")
            .order_by(Receipt.created_at.desc(), Receipt.id.desc())
            .all()
        )
        picked = [
            r
            for r in candidates
            if _is_image(r) and _has_scoreable_ocr(r) and item_counts[r.id] >= MIN_ITEMS
        ][:wanted]
        if len(picked) < wanted:
            raise SystemExit(f"{store}: only {len(picked)} eligible receipts, wanted {wanted}.")
        chosen.extend((store, r, item_counts[r.id]) for r in picked)
    return chosen


def write(chosen: list[tuple[str, Receipt, int]], output: Path) -> None:
    lines = [
        "# CM-15 eval set: 30 image receipts. Generated by select_cm15_set.py.",
        "# One receipt id per line. Lines starting with # are ignored.",
        "# Pass to ocr_eval.py with:  --receipt-ids $(grep -v '^#' <this file>)",
    ]
    current = None
    for store, receipt, items in chosen:
        if store != current:
            lines.append(f"# {store}")
            current = store
        lines.append(f"{receipt.id}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_ids(path: Path) -> list[int]:
    return [
        int(line.strip())
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def check(db, path: Path) -> int:
    """Confirm the frozen set is usable on this machine. Returns an exit code."""
    ids = read_ids(path)
    item_counts = Counter(rid for (rid,) in db.query(ReceiptItem.receipt_id).all())
    receipts = {r.id: r for r in db.query(Receipt).filter(Receipt.id.in_(ids)).all()}

    problems: list[str] = []
    if len(ids) != len(set(ids)):
        problems.append("the list contains duplicate ids")
    for rid in ids:
        receipt = receipts.get(rid)
        if receipt is None:
            problems.append(f"receipt {rid} is not in this database")
            continue
        if not _is_image(receipt):
            problems.append(f"receipt {rid} is not an image receipt")
        if not _has_scoreable_ocr(receipt) or item_counts[rid] == 0:
            problems.append(f"receipt {rid} is not scoreable")
        if receipt.image_path and not os.path.exists(receipt.image_path):
            problems.append(f"receipt {rid}: image not found at {receipt.image_path}")

    print(f"{len(ids)} receipts in {path.name}")
    if problems:
        for problem in problems:
            print(f"  - {problem}")
        print(f"{len(problems)} problem(s). Fix these before running the model.")
        return 1
    print("All present, scoreable, and every image is on disk.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Choose or check the CM-15 eval set.")
    parser.add_argument("--check", action="store_true", help="verify the frozen list")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    db = SessionLocal()
    try:
        if args.check:
            return check(db, args.output)

        chosen = choose(db)
        write(chosen, args.output)
        for store, receipt, items in chosen:
            print(f"{store:20s} {receipt.id:4d}  items={items:3d}  {receipt.image_path}")
        prefixes = Counter(os.path.dirname(r.image_path) for _, r, _ in chosen)
        print(f"\nWrote {len(chosen)} ids to {args.output}")
        print("Image directories used:")
        for prefix, count in prefixes.items():
            print(f"  {count:2d}  {prefix}")
        return 0
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
